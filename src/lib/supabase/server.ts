import { createServerClient } from '@supabase/ssr';
import { cookies } from 'next/headers';

/**
 * Check if a real Supabase configuration is present.
 * Prevents hanging network calls to placeholder URLs.
 */
export function isSupabaseConfigured(): boolean {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const anonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  return Boolean(
    url &&
    !url.includes('placeholder') &&
    !url.includes('example') &&
    anonKey &&
    !anonKey.includes('placeholder')
  );
}

/**
 * Create a Supabase client for use in Server Components, Server Actions,
 * and Route Handlers. Reads/writes auth cookies via Next.js cookies() API.
 */
export async function createClient() {
  const cookieStore = await cookies();
  const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL || 'https://placeholder.supabase.co';
  const supabaseAnonKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || 'placeholder-anon-key';

  return createServerClient(
    supabaseUrl,
    supabaseAnonKey,
    {
      cookies: {
        getAll() {
          return cookieStore.getAll();
        },
        setAll(cookiesToSet) {
          try {
            cookiesToSet.forEach(({ name, value, options }) =>
              cookieStore.set(name, value, options)
            );
          } catch {
            // The `setAll` method was called from a Server Component.
            // This can be ignored if you have middleware refreshing sessions.
          }
        },
      },
    }
  );
}

/**
 * Create a Supabase admin client with the service role key.
 * ONLY use this in server-side code for admin operations that
 * bypass RLS (e.g., verification status updates, system notifications).
 */
